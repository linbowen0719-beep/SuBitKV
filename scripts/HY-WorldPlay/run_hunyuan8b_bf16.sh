#!/bin/bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

PYTHON="${PYTHON:-python}"
: "${MODEL_PATH:?set MODEL_PATH or SUBITKV_HY8B_MODEL}"
: "${ACTION_CKPT:?set ACTION_CKPT or SUBITKV_HY_ACTION_CKPT}"
IMAGE_PATH="${IMAGE_PATH:-$REPO_ROOT/assets/hyworld.png}"
OUTPUT_PATH="${OUTPUT_PATH:-$REPO_ROOT/results/hunyuan8b_hyvideo_bf16_61f}"

PROMPT="${PROMPT:-A first-person exploration video moving steadily through a detailed natural scene, maintaining geometric consistency and smooth camera motion.}"
NEGATIVE_PROMPT="${NEGATIVE_PROMPT:-}"
POSE="${POSE:-w-15}"
VIDEO_LENGTH="${VIDEO_LENGTH:-61}"
SEED="${SEED:-123}"
NUM_INFERENCE_STEPS="${NUM_INFERENCE_STEPS:-4}"
NUM_GPUS="${NUM_GPUS:-1}"
MASTER_PORT="${MASTER_PORT:-29573}"

RESOLUTION="${RESOLUTION:-480p}"
ASPECT_RATIO="${ASPECT_RATIO:-16:9}"
DTYPE="${DTYPE:-bf16}"
SR="${SR:-false}"
REWRITE="${REWRITE:-false}"
FEW_STEP="${FEW_STEP:-true}"
OFFLOADING="${OFFLOADING:-true}"
KV_CACHE_OFFLOAD="${KV_CACHE_OFFLOAD:-false}"
KV_CACHE_GPU_RESIDENT_COMPRESSED="${KV_CACHE_GPU_RESIDENT_COMPRESSED:-false}"
FULL_HISTORY_ATTENTION="${FULL_HISTORY_ATTENTION:-false}"
APPEND_ONLY_VISION_CACHE="${APPEND_ONLY_VISION_CACHE:-false}"
KV_CACHE_CODEC="${KV_CACHE_CODEC:-none}"
KV_CODEC_K_CODEBOOK_DIR="${KV_CODEC_K_CODEBOOK_DIR:-}"
KV_CODEC_V_CODEBOOK_DIR="${KV_CODEC_V_CODEBOOK_DIR:-}"
KV_CODEC_ROUTING_PATH="${KV_CODEC_ROUTING_PATH:-}"
KV_CODEC_TREE_PATH="${KV_CODEC_TREE_PATH:-}"
KV_CODEC_V_PARAMS_PATH="${KV_CODEC_V_PARAMS_PATH:-}"
KV_CODEC_TEMPORAL_PROFILE_PATH="${KV_CODEC_TEMPORAL_PROFILE_PATH:-}"
KV_CODEC_FRAME_SPATIAL_TOKENS="${KV_CODEC_FRAME_SPATIAL_TOKENS:-1537}"
KV_CAPTURE_DIR="${KV_CAPTURE_DIR:-}"
KV_CAPTURE_PROMPT_INDEX="${KV_CAPTURE_PROMPT_INDEX:--1}"
KV_CAPTURE_SAMPLE_TOKENS="${KV_CAPTURE_SAMPLE_TOKENS:-1250}"
KV_CAPTURE_SEED="${KV_CAPTURE_SEED:-42}"
KV_CAPTURE_HISTORY_CALLS="${KV_CAPTURE_HISTORY_CALLS:-9}"
KV_RESIDUAL_STATS_DIR="${KV_RESIDUAL_STATS_DIR:-}"
KV_RESIDUAL_STATS_PROMPT_INDEX="${KV_RESIDUAL_STATS_PROMPT_INDEX:--1}"
KV_RESIDUAL_STATS_SAMPLES_PER_HEAD="${KV_RESIDUAL_STATS_SAMPLES_PER_HEAD:-128}"
KV_RESIDUAL_STATS_SEED="${KV_RESIDUAL_STATS_SEED:-42}"
KV_AVG2_CALIBRATION_DIR="${KV_AVG2_CALIBRATION_DIR:-}"
KV_AVG2_CALIBRATION_PROMPT_INDEX="${KV_AVG2_CALIBRATION_PROMPT_INDEX:--1}"
KV_AVG2_CALIBRATION_QUERIES_PER_STREAM="${KV_AVG2_CALIBRATION_QUERIES_PER_STREAM:-4}"
KV_AVG2_CALIBRATION_SEED="${KV_AVG2_CALIBRATION_SEED:-42}"
RECORD_LATENT_HASHES="${RECORD_LATENT_HASHES:-false}"
TERMINAL_CACHE_AUDIT="${TERMINAL_CACHE_AUDIT:-false}"
HEIGHT="${HEIGHT:-464}"
WIDTH="${WIDTH:-848}"
GROUP_OFFLOADING="${GROUP_OFFLOADING:-false}"
USE_SAGEATTN="${USE_SAGEATTN:-false}"
USE_FP8_GEMM="${USE_FP8_GEMM:-false}"
USE_VAE_PARALLEL="${USE_VAE_PARALLEL:-false}"
ENABLE_TORCH_COMPILE="${ENABLE_TORCH_COMPILE:-false}"
FP8_QUANT_TYPE="${FP8_QUANT_TYPE:-fp8-per-block}"
INCLUDE_PATTERNS="${INCLUDE_PATTERNS:-double_blocks}"
SAGE_BLOCKS_RANGE="${SAGE_BLOCKS_RANGE:-0-53}"

: "${CUDA_VISIBLE_DEVICES:=0}"
: "${PYTORCH_CUDA_ALLOC_CONF:=expandable_segments:True}"
export CUDA_VISIBLE_DEVICES PYTORCH_CUDA_ALLOC_CONF
export PYTHONPATH="$REPO_ROOT:$REPO_ROOT/experiments/HY-WorldPlay${PYTHONPATH:+:$PYTHONPATH}"

cmd=(
  "$PYTHON" -m torch.distributed.run
  "--nproc_per_node=$NUM_GPUS"
  "--master_port=$MASTER_PORT"
  "$REPO_ROOT/experiments/HY-WorldPlay/hyvideo/generate.py"
  --prompt "$PROMPT"
  --negative_prompt "$NEGATIVE_PROMPT"
  --image_path "$IMAGE_PATH"
  --resolution "$RESOLUTION"
  --aspect_ratio "$ASPECT_RATIO"
  --video_length "$VIDEO_LENGTH"
  --seed "$SEED"
  --rewrite "$REWRITE"
  --sr "$SR"
  --pose "$POSE"
  --output_path "$OUTPUT_PATH"
  --model_path "$MODEL_PATH"
  --action_ckpt "$ACTION_CKPT"
  --few_step "$FEW_STEP"
  --num_inference_steps "$NUM_INFERENCE_STEPS"
  --model_type ar
  --dtype "$DTYPE"
  --offloading "$OFFLOADING"
  --kv_cache_offload "$KV_CACHE_OFFLOAD"
  --kv_cache_gpu_resident_compressed "$KV_CACHE_GPU_RESIDENT_COMPRESSED"
  --full_history_attention "$FULL_HISTORY_ATTENTION"
  --append_only_vision_cache "$APPEND_ONLY_VISION_CACHE"
  --kv_cache_codec "$KV_CACHE_CODEC"
  --kv_codec_k_codebook_dir "$KV_CODEC_K_CODEBOOK_DIR"
  --kv_codec_v_codebook_dir "$KV_CODEC_V_CODEBOOK_DIR"
  --kv_codec_routing_path "$KV_CODEC_ROUTING_PATH"
  --kv_codec_tree_path "$KV_CODEC_TREE_PATH"
  --kv_codec_v_params_path "$KV_CODEC_V_PARAMS_PATH"
  --kv_codec_temporal_profile_path "$KV_CODEC_TEMPORAL_PROFILE_PATH"
  --kv_codec_frame_spatial_tokens "$KV_CODEC_FRAME_SPATIAL_TOKENS"
  --kv_capture_dir "$KV_CAPTURE_DIR"
  --kv_capture_prompt_index "$KV_CAPTURE_PROMPT_INDEX"
  --kv_capture_sample_tokens "$KV_CAPTURE_SAMPLE_TOKENS"
  --kv_capture_seed "$KV_CAPTURE_SEED"
  --kv_capture_history_calls "$KV_CAPTURE_HISTORY_CALLS"
  --kv_residual_stats_dir "$KV_RESIDUAL_STATS_DIR"
  --kv_residual_stats_prompt_index "$KV_RESIDUAL_STATS_PROMPT_INDEX"
  --kv_residual_stats_samples_per_head "$KV_RESIDUAL_STATS_SAMPLES_PER_HEAD"
  --kv_residual_stats_seed "$KV_RESIDUAL_STATS_SEED"
  --kv_avg2_calibration_dir "$KV_AVG2_CALIBRATION_DIR"
  --kv_avg2_calibration_prompt_index "$KV_AVG2_CALIBRATION_PROMPT_INDEX"
  --kv_avg2_calibration_queries_per_stream "$KV_AVG2_CALIBRATION_QUERIES_PER_STREAM"
  --kv_avg2_calibration_seed "$KV_AVG2_CALIBRATION_SEED"
  --record_latent_hashes "$RECORD_LATENT_HASHES"
  --terminal_cache_audit "$TERMINAL_CACHE_AUDIT"
  --height "$HEIGHT"
  --width "$WIDTH"
  --group_offloading "$GROUP_OFFLOADING"
  --use_sageattn "$USE_SAGEATTN"
  --use_fp8_gemm "$USE_FP8_GEMM"
  --use_vae_parallel "$USE_VAE_PARALLEL"
  --enable_torch_compile "$ENABLE_TORCH_COMPILE"
  --quant_type "$FP8_QUANT_TYPE"
  --include_patterns "$INCLUDE_PATTERNS"
  --sage_blocks_range "$SAGE_BLOCKS_RANGE"
  "$@"
)

mkdir -p "$OUTPUT_PATH"
cd "$REPO_ROOT"

printf 'Running HunyuanVideo-1.5 / HY-WorldPlay via hyvideo:\n'
printf '  output: %s/gen.mp4\n' "$OUTPUT_PATH"
printf '  command:'
printf ' %q' "${cmd[@]}"
printf '\n'

if [[ "${DRY_RUN:-0}" == "1" ]]; then
  exit 0
fi

"${cmd[@]}"
